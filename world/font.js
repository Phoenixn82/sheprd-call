  // Render one line of text into a Grid. ink/paper are palette chars; paper '.' = transparent.
  SH.textGrid = function (text, fontName, ink, paper) {
    const f = SH.FONTS[fontName];
    if (f.upper) text = text.toUpperCase();
    const glyphs = [...text].map(c => f.glyphs[c] || f.glyphs[f.fallback]);
    const w = Math.max(1, glyphs.reduce((sum, rows) => sum + rows[0].length + f.adv - f.w, 0) - (f.adv - f.w));
    const g = new G(w, f.h, paper === undefined ? '.' : paper);
    let x = 0;
    for (const rows of glyphs) { g.stamp(rows, x, 0, { '#': ink }); x += rows[0].length + f.adv - f.w; }
    return g;
  };

  // Greedy word wrap to `cols` characters per line.
  SH.wrap = function (text, cols) {
    const lines = []; let line = '';
    for (const word of text.split(' ')) {
      if (line && (line + ' ' + word).length > cols) { lines.push(line); line = word; }
      else line = line ? line + ' ' + word : word;
    }
    if (line) lines.push(line);
    return lines;
  };
